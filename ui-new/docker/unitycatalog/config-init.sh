#!/bin/sh
# Prepares what the server starts from: creates the bucket in RustFS, then
# writes the configuration volume, the repository's etc/conf with local
# PostgreSQL and storage overrides, plus the fallback credential encryption
# key, and gives the volume to the server's user.

set -eu

endpoint="${RUSTFS_ENDPOINT:-http://rustfs:9000}"
# Fixed, not a setting: once anything uses the external location storage-init
# registers for it, the server refuses to move the location to another bucket.
bucket=uc-warehouse
postgres_host="${POSTGRES_HOST:-postgres}"
postgres_db="${POSTGRES_DB:-ucdb}"
postgres_user="${POSTGRES_USER:-uc_default_user}"
# The volume, the templates and the volume's owner; config-init-test.sh points
# them elsewhere. The owner is the server image's user and group, which the
# Helm chart also gives etc/conf.
conf="${CONF_DIR:-/conf}"
templates="${TEMPLATES_DIR:-/templates}"
uc_owner="${CONF_OWNER:-100:101}"
encryption_key_file="$conf/credential-encryption.key"

export AWS_ACCESS_KEY_ID="${RUSTFS_ACCESS_KEY:-rustfsadmin}"
export AWS_SECRET_ACCESS_KEY="${RUSTFS_SECRET_KEY:-rustfsadmin}"
export AWS_DEFAULT_REGION=us-east-1

log() {
  echo "[config-init] $*"
}

log "waiting for RustFS at $endpoint"
attempt=0
until aws --endpoint-url "$endpoint" s3api list-buckets >/dev/null 2>&1; do
  attempt=$((attempt + 1))
  if [ "$attempt" -ge 60 ]; then
    log "RustFS did not become ready in time" >&2
    exit 1
  fi
  sleep 2
done

if ! aws --endpoint-url "$endpoint" s3api head-bucket --bucket "$bucket" >/dev/null 2>&1; then
  log "creating s3://$bucket"
  aws --endpoint-url "$endpoint" s3api create-bucket --bucket "$bucket" >/dev/null
fi

# Each file is written beside its final name and renamed into place, so a server
# that `docker compose restart` starts alongside this never reads a template
# without its overrides.
mkdir -p "$conf"
for template in "$templates"/*.properties; do
  cp -f "$template" "$conf/.$(basename "$template").tmp"
done

# storage-init registers RustFS as an s3_compatible storage credential.
# Authorization stays off: the stack sets up no identity provider.
{
  printf '\n# Local Compose overrides generated by config-init.\n'
  printf 'server.authorization=disable\n'
  printf 'server.s3-compatible-storage.enabled=true\n'
  printf 'storage-root.tables=s3://%s\n' "$bucket"
} >> "$conf/.server.properties.tmp"

# The password comes from UC_HIBERNATE_CONNECTION_PASSWORD, as in the Helm chart.
{
  printf '\n# Local Compose overrides generated by config-init.\n'
  printf 'hibernate.connection.driver_class=org.postgresql.Driver\n'
  printf 'hibernate.connection.url=jdbc:postgresql://%s:5432/%s\n' "$postgres_host" "$postgres_db"
  printf 'hibernate.connection.username=%s\n' "$postgres_user"
} >> "$conf/.hibernate.properties.tmp"

# Only the files this run wrote, so a leftover from an interrupted run, for a
# template since removed, is never put in place.
for template in "$templates"/*.properties; do
  name="$(basename "$template")"
  mv -f "$conf/.$name.tmp" "$conf/$name"
done

# The server encrypts that credential's secret with
# UC_SERVER_CREDENTIAL_ENCRYPTION_KEY; when the variable is empty it uses this
# key, generated once and kept with the volume. It is written beside its final
# name and renamed, so an interrupted run can't leave a partial key that this
# check would then keep.
if [ ! -s "$encryption_key_file" ]; then
  log "generating the fallback credential encryption key"
  (umask 077 && head -c 32 /dev/urandom | base64 > "$encryption_key_file.tmp")
  mv -f "$encryption_key_file.tmp" "$encryption_key_file"
fi
chmod 600 "$encryption_key_file"

# This container runs as root; the server runs as uid 100 and writes its signing
# keys and token.txt here, so the volume must be its own whatever ran first.
chown -R "$uc_owner" "$conf"
chmod u+rwx "$conf"

log "configured Unity Catalog for s3://$bucket"
